"""
Build the Business Brief vector brand assets.

Writes outlined SVG masters (text converted to paths, so they render the same
anywhere, without the typefaces installed) into public/brand/. The typefaces are
the self-hosted ones in public/fonts, all under the SIL Open Font Licence.

The AA monogram is NOT generated here: it is the creator's authentic mark,
copied unchanged from the Economics repository (see public/brand/creator/README.md).

Requirements (not needed to build the website):
    python3 -m pip install fonttools brotli uharfbuzz
Run from the repository root:
    python3 scripts/brand/build_brand.py
"""

from __future__ import annotations

import io
from dataclasses import dataclass
from pathlib import Path

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

ROOT = Path(__file__).resolve().parents[2]
FONTS = ROOT / "public" / "fonts"
OUT = ROOT / "public" / "brand"

INK = "#111417"
PAPER = "#F4F1EA"
SLATE = "#65717C"
COBALT = "#315CFF"
BRASS = "#C79A45"
ON_INK_MUTED = "#B8BEC4"

HEADER = "<!-- Arjun Agrawal | The Business Brief. Vector master generated by scripts/brand/build_brand.py. Text set in Inter Tight and IBM Plex Mono (SIL Open Font Licence 1.1), converted to outlines. -->"


@dataclass
class Face:
    font: TTFont
    hb_font: hb.Font
    upem: int


def load_face(filename: str, weight: float | None = None) -> Face:
    font = TTFont(FONTS / filename)
    if weight is not None and "fvar" in font:
        font = instantiateVariableFont(font, {"wght": weight}, inplace=False)
    font.flavor = None
    buf = io.BytesIO()
    font.save(buf)
    data = buf.getvalue()
    font = TTFont(io.BytesIO(data))
    blob = hb.Blob(data)
    hb_face = hb.Face(blob)
    hb_font = hb.Font(hb_face)
    upem = font["head"].unitsPerEm
    hb_font.scale = (upem, upem)
    return Face(font=font, hb_font=hb_font, upem=upem)


def text_path(face: Face, text: str, size: float, x: float, baseline: float, tracking_em: float = 0.0) -> tuple[str, float]:
    """Return SVG path data for `text` and the advance width, in output units."""
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(face.hb_font, buf, {"kern": True, "liga": True})
    glyph_order = face.font.getGlyphOrder()
    glyph_set = face.font.getGlyphSet()
    scale = size / face.upem
    pen = SVGPathPen(glyph_set)
    cursor = 0.0
    infos, positions = buf.glyph_infos, buf.glyph_positions
    for i, (info, pos) in enumerate(zip(infos, positions)):
        name = glyph_order[info.codepoint]
        gx = x + (cursor + pos.x_offset) * scale
        gy = baseline - pos.y_offset * scale
        tpen = TransformPen(pen, (scale, 0, 0, -scale, gx, gy))
        glyph_set[name].draw(tpen)
        cursor += pos.x_advance
        if i < len(infos) - 1:
            cursor += tracking_em * face.upem
    return pen.getCommands(), cursor * scale


def bounds_of(face: Face, text: str, size: float, tracking_em: float = 0.0) -> tuple[float, float, float, float]:
    """Ink bounds of the shaped text at origin (0, 0) baseline, in output units (y down)."""
    buf = hb.Buffer()
    buf.add_str(text)
    buf.guess_segment_properties()
    hb.shape(face.hb_font, buf, {"kern": True, "liga": True})
    glyph_order = face.font.getGlyphOrder()
    glyph_set = face.font.getGlyphSet()
    scale = size / face.upem
    bpen = BoundsPen(glyph_set)
    cursor = 0.0
    infos, positions = buf.glyph_infos, buf.glyph_positions
    for i, (info, pos) in enumerate(zip(infos, positions)):
        name = glyph_order[info.codepoint]
        tpen = TransformPen(bpen, (scale, 0, 0, -scale, (cursor + pos.x_offset) * scale, -pos.y_offset * scale))
        glyph_set[name].draw(tpen)
        cursor += pos.x_advance
        if i < len(infos) - 1:
            cursor += tracking_em * face.upem
    b = bpen.bounds or (0, 0, 0, 0)
    return b


def mark(x: float, y: float, s: float, reversed_: bool = False, mono: str | None = None) -> str:
    """The decision mark, drawn on a 64-unit grid and placed at (x, y) with side s.

    A brief (a document with a folded corner), a decision node, the path taken
    and the path not taken.
    """
    k = s / 64.0

    def p(px: float, py: float) -> str:
        return f"{x + px * k:.2f} {y + py * k:.2f}"

    doc = INK if not reversed_ else PAPER
    fold = BRASS
    taken = PAPER if not reversed_ else INK
    alt = SLATE
    node = COBALT
    if mono:
        doc, fold, taken, alt, node = mono, mono, "none", "none", "none"
    sw = 5.5 * k
    parts = [
        f'<path d="M{p(0, 0)}L{p(46, 0)}L{p(64, 18)}L{p(64, 64)}L{p(0, 64)}Z" fill="{doc}"/>',
    ]
    if mono:
        # Single-colour version: the paths are knocked out of the document.
        parts = [
            f'<mask id="m"><rect x="{x:.2f}" y="{y:.2f}" width="{s:.2f}" height="{s:.2f}" fill="#fff"/>'
            f'<path d="M{p(46, 0)}L{p(46, 18)}L{p(64, 18)}" fill="none" stroke="#000" stroke-width="{2.5 * k:.2f}"/>'
            f'<path d="M{p(9, 38)}L{p(28, 38)}L{p(48, 24)}M{p(28, 38)}L{p(48, 52)}" fill="none" stroke="#000" stroke-width="{sw:.2f}"/>'
            f'<circle cx="{x + 28 * k:.2f}" cy="{y + 38 * k:.2f}" r="{6.5 * k:.2f}" fill="#000"/></mask>',
            f'<path mask="url(#m)" d="M{p(0, 0)}L{p(46, 0)}L{p(64, 18)}L{p(64, 64)}L{p(0, 64)}Z" fill="{doc}"/>',
        ]
        return "".join(parts)
    parts += [
        f'<path d="M{p(46, 0)}L{p(46, 18)}L{p(64, 18)}Z" fill="{fold}"/>',
        f'<path d="M{p(28, 38)}L{p(48, 52)}" fill="none" stroke="{alt}" stroke-width="{sw:.2f}"/>',
        f'<path d="M{p(9, 38)}L{p(28, 38)}L{p(48, 24)}" fill="none" stroke="{taken}" stroke-width="{sw:.2f}" stroke-linejoin="miter"/>',
        f'<circle cx="{x + 28 * k:.2f}" cy="{y + 38 * k:.2f}" r="{6 * k:.2f}" fill="{node}"/>',
    ]
    return "".join(parts)


def svg(view_w: float, view_h: float, body: str, title: str, bg: str | None = None) -> str:
    bg_rect = f'<rect width="{view_w:.2f}" height="{view_h:.2f}" fill="{bg}"/>' if bg else ""
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f"{HEADER}\n"
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {view_w:.2f} {view_h:.2f}" role="img" aria-label="{title}">'
        f"<title>{title}</title>{bg_rect}{body}</svg>\n"
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    display = load_face("inter-tight-latin-wght-normal.woff2", weight=700)
    mono = load_face("ibm-plex-mono-latin-500-normal.woff2")

    # 1. The mark
    for name, rev in (("business-brief-mark.svg", False), ("business-brief-mark-reversed.svg", True)):
        (OUT / name).write_text(svg(64, 64, mark(0, 0, 64, reversed_=rev), "The Business Brief mark"), encoding="utf-8")
    (OUT / "business-brief-mark-mono.svg").write_text(svg(64, 64, mark(0, 0, 64, mono=INK), "The Business Brief mark, single colour"), encoding="utf-8")
    # Favicon: the mark on its own
    (ROOT / "public" / "favicon.svg").write_text(svg(64, 64, mark(0, 0, 64), "The Business Brief"), encoding="utf-8")

    # 2. Horizontal lockup: mark | ARJUN AGRAWAL over The Business Brief
    for name, rev in (("business-brief-lockup.svg", False), ("business-brief-lockup-reversed.svg", True)):
        title_color = INK if not rev else PAPER
        kicker_color = SLATE if not rev else ON_INK_MUTED
        m = 64.0
        gap = 18.0
        title_size = 38.0
        kicker_size = 13.0
        tx = m + gap
        kicker_d, kicker_w = text_path(mono, "ARJUN AGRAWAL", kicker_size, tx, 20.0, tracking_em=0.16)
        title_d, title_w = text_path(display, "The Business Brief", title_size, tx - 1.5, 58.0, tracking_em=-0.022)
        width = tx + max(kicker_w, title_w) + 2
        body = (
            mark(0, 0, m, reversed_=rev)
            + f'<path d="{kicker_d}" fill="{kicker_color}"/>'
            + f'<path d="{title_d}" fill="{title_color}"/>'
        )
        (OUT / name).write_text(svg(width, 64, body, "Arjun Agrawal | The Business Brief"), encoding="utf-8")

    # 3. Stacked lockup with the tagline
    for name, rev in (("business-brief-lockup-stacked.svg", False), ("business-brief-lockup-stacked-reversed.svg", True)):
        title_color = INK if not rev else PAPER
        kicker_color = SLATE if not rev else ON_INK_MUTED
        m = 96.0
        title_size = 56.0
        kicker_size = 15.0
        tag_size = 15.0
        kicker_d, kicker_w = text_path(mono, "ARJUN AGRAWAL", kicker_size, 0, m + 44, tracking_em=0.16)
        title_d, title_w = text_path(display, "The Business Brief", title_size, -2, m + 104, tracking_em=-0.022)
        tag_d, tag_w = text_path(mono, "STRATEGY. LEADERSHIP. DECISIONS.", tag_size, 0, m + 146, tracking_em=0.12)
        width = max(kicker_w, title_w, tag_w) + 4
        body = (
            mark(0, 0, m, reversed_=rev)
            + f'<path d="{kicker_d}" fill="{kicker_color}"/>'
            + f'<path d="{title_d}" fill="{title_color}"/>'
            + f'<rect x="0" y="{m + 118:.2f}" width="{width - 4:.2f}" height="1.5" fill="{kicker_color}"/>'
            + f'<path d="{tag_d}" fill="{title_color}"/>'
        )
        (OUT / name).write_text(svg(width, m + 156, body, "Arjun Agrawal | The Business Brief. Strategy. Leadership. Decisions."), encoding="utf-8")

    # 4. Wordmark alone (no mark), for narrow placements and document headers
    for name, rev in (("business-brief-wordmark.svg", False), ("business-brief-wordmark-reversed.svg", True)):
        title_color = INK if not rev else PAPER
        title_d, title_w = text_path(display, "The Business Brief", 40.0, 0, 38.0, tracking_em=-0.022)
        (OUT / name).write_text(svg(title_w + 2, 48, f'<path d="{title_d}" fill="{title_color}"/>', "The Business Brief"), encoding="utf-8")

    print("Brand SVGs written to", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
